|   SHOP_API_TIMEOUT=10                     — таймаут запросов (сек)
|
| ShopApiService сам логинится по этим данным, кеширует JWT-токен
| и обновляет его при истечении.
|
*/

return [

    // Базовый URL магазина (без завершающего слеша — слеш обрезается в сервисе)
    'base_url' => env('SHOP_API_URL', 'http://localhost:8001'),

    // Учётные данные для автологина в магазин
    'email'    => env('SHOP_API_EMAIL'),
    'password' => env('SHOP_API_PASSWORD'),

    // Таймаут HTTP-запросов к магазину, секунд
    'timeout'  => env('SHOP_API_TIMEOUT', 10),

];
